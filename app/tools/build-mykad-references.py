"""Build the private, immutable model-reference module from reviewed local specimens.

No network access. Never place these references in the public asset directory.
"""
import base64
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CATALOG = ROOT / 'research/mykad-references/catalog.json'


def main():
    catalog = json.loads(CATALOG.read_text(encoding='utf-8'))
    references = []
    for item in catalog['references']:
        path = (CATALOG.parent / item['file']).resolve()
        assert path.is_relative_to(CATALOG.parent.resolve()), 'Reference path escapes catalog'
        data = path.read_bytes()
        assert hashlib.sha256(data).hexdigest() == item['sha256'], f'Unreviewed reference change: {item["id"]}'
        assert data.startswith(b'\xff\xd8\xff') and len(data) < 1024 * 1024, 'Expected bounded JPEG'
        references.append({key: item[key] for key in ('id', 'label', 'sha256')}
                          | {'imageUrl': 'data:image/jpeg;base64,' + base64.b64encode(data).decode('ascii')})
    output = '// Generated by tools/build-mykad-references.py. Private server module.\n'
    output += 'export const MYKAD_REFERENCE_VERSION = ' + json.dumps(catalog['version']) + ';\n'
    output += 'export const MYKAD_REFERENCES = Object.freeze(' + json.dumps(references, separators=(',', ':')) + '.map(Object.freeze));\n'
    (ROOT / 'deploy/mykad-reference-data.js').write_text(output, encoding='utf-8')
    print(f'Bundled {len(references)} reviewed MyKad layout references ({catalog["version"]}).')


if __name__ == '__main__':
    main()
